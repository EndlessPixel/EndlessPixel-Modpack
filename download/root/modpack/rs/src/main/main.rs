// --------------------------------------------------------------------------------------------
fn main() {
    // --------------------------------------------------------------------------------------------
    let url = "https://www.endlesspixel.fun/downloads/modpack";
    // --------------------------------------------------------------------------------------------
    #[cfg(target_os = "windows")]
    // --------------------------------------------------------------------------------------------
    std::process::Command::new("cmd")
    // --------------------------------------------------------------------------------------------
        .args(&["/C", "start", ""])
        // --------------------------------------------------------------------------------------------
        .arg(url)
        // --------------------------------------------------------------------------------------------
        .spawn()
        // --------------------------------------------------------------------------------------------
        .unwrap();
        // --------------------------------------------------------------------------------------------
    #[cfg(target_os = "macos")]
    // --------------------------------------------------------------------------------------------
    std::process::Command::new("open").arg(url).spawn().unwrap();
    // --------------------------------------------------------------------------------------------
    #[cfg(target_family = "unix")]
    // --------------------------------------------------------------------------------------------
    std::process::Command::new("xdg-open").arg(url).spawn().unwrap();
    // --------------------------------------------------------------------------------------------
}
// --------------------------------------------------------------------------------------------